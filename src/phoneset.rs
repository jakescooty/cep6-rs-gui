fn feat(phone: &str, col: usize) -> &'static str {
    match PHONES.iter().find(|p| p.0 == phone) {
        Some(p) => match col {
            0 => p.1, 1 => p.2, 2 => p.3, 3 => p.4, 4 => p.5,
            5 => p.6, 6 => p.7, 7 => p.8, 8 => p.9, _ => p.10,
        },
        None => "0",
    }
}

/// `vc` is `+`: the phone is a vowel.
pub fn is_vowel(phone: &str) -> bool {
    feat(phone, 0) == "+"
}

/// `cvox` is `+`: the phone is a voiced consonant. Vowels carry `0` here, not
/// `+`, which is why every caller in swift.dll tests `vc` before `cvox`.
pub fn is_voiced_consonant(phone: &str) -> bool {
    feat(phone, 9) == "+"
}

/// `vc` and `cvox` as the CARTs read them -- `+`, `-` or `0` -- rather than as
/// the booleans the target cost wants. A duration tree tests the raw string, and
/// `0` is a third case it distinguishes from `-`.
pub fn vc(phone: &str) -> &'static str {
    feat(phone, 0)
}

pub fn cvox(phone: &str) -> &'static str {
    feat(phone, 9)
}

/// `ctype`: `s` stop, `f` fricative, `a` affricate, `n` nasal, `l` approximant,
/// `0` for anything that is not a consonant.
pub fn ctype(phone: &str) -> &'static str {
    feat(phone, 6)
}

/// `cplace`: `b` labial, `d` dental, `a` alveolar, `p` palatal, `v` velar,
/// `g` glottal, `r` retroflex, `la` lateral.
pub fn cplace(phone: &str) -> &'static str {
    feat(phone, 7)
}

/// `vrnd` is `+`: a rounded vowel.
pub fn is_rounded(phone: &str) -> bool {
    feat(phone, 3) == "+"
}

pub fn vheight(phone: &str) -> &'static str {
    feat(phone, 1)
}

pub fn vfront(phone: &str) -> &'static str {
    feat(phone, 2)
}

pub fn vlng(phone: &str) -> &'static str {
    feat(phone, 4)
}

pub fn known(phone: &str) -> bool {
    PHONES.iter().any(|p| p.0 == phone)
}
